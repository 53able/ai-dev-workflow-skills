#!/usr/bin/env python3
"""Serial live container probes with private auth excluded from provenance.

Requires the public workspace generated by prepare.py and a frozen candidate.
Never resumes. Each launch uses a new private Codex auth cache, which is not
hashed or published. API keys are not passed into containers.
"""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[2]
# Reserved wrapper exit for a failed evidence collector. An agent that exits with
# the same value is also treated as a collection failure (fails closed).
COLLECT_FAILED_EXIT = 86
COLLECTED_EVIDENCE = ('consumer-preservation.json', 'postcheck.json')


class AuthenticationUnavailable(RuntimeError):
    pass


class EvidenceValidationError(RuntimeError):
    pass


def publish(path: Path, data: bytes) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix='.publish-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'wb') as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def digest_tree(root: Path) -> dict[str, str]:
    result = {}
    for p in sorted(root.rglob('*')):
        if p.is_symlink(): raise ValueError('symlink in public inputs')
        if p.is_file(): result[str(p.relative_to(root))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return result



def auth_strings(path: Path) -> set[str]:
    if not path.exists():
        return set()
    def visit(value):
        if isinstance(value, dict):
            for item in value.values(): yield from visit(item)
        elif isinstance(value, list):
            for item in value: yield from visit(item)
        elif isinstance(value, str) and value:
            yield value
    return set(visit(json.loads(path.read_text())))


def redact(data: bytes, values: set[str]) -> bytes:
    needles = sorted((x.encode() for x in values if x), key=len, reverse=True)
    while True:
        before = data
        for value in needles:
            data = data.replace(value, b'')
        if data == before:
            break
    if any(value in data for value in needles):
        raise EvidenceValidationError('redaction final-byte check failed')
    return data


def capture(argv, *, env, name, timeout=240):
    started = time.monotonic()
    try:
        result = subprocess.run(argv, capture_output=True, env=env, timeout=timeout)
        return result.stdout + b'\n' + result.stderr, {'exitCode': result.returncode, 'durationSeconds': round(time.monotonic()-started, 3), 'status': 'observed; requires event and filesystem adjudication'}
    except subprocess.TimeoutExpired as error:
        data = (error.stdout or b'') + b'\n' + (error.stderr or b'')
        try:
            cleanup = subprocess.run(['container', 'rm', '-f', name], capture_output=True, timeout=10)
            cleanup_status = 'complete' if cleanup.returncode == 0 else 'cleanup failure'
        except (subprocess.TimeoutExpired, OSError):
            cleanup_status = 'cleanup failure'
        return data, {'status':'timeout', 'timeoutSeconds':timeout, 'cleanup':cleanup_status, 'durationSeconds':round(time.monotonic()-started, 3)}


def sanitize_artifacts(root: Path, values: set[str]) -> list[str]:
    altered = []
    # Remove secret-bearing path names before any path reaches diagnostics.
    for index, path in enumerate(sorted(root.rglob('*'), key=lambda p: len(p.parts), reverse=True)):
        if any(value and value in path.name for value in values):
            replacement = path.with_name('redacted-path-' + str(index))
            if replacement.exists():
                raise EvidenceValidationError('unsafe evidence path collision')
            path.rename(replacement)
            altered.append('secret-bearing path renamed')
    for path in root.rglob('*'):
        if path.is_symlink():
            raise EvidenceValidationError('unexpected evidence symlink')
        if path.is_file():
            data = path.read_bytes()
            safe = redact(data, values)
            if safe != data:
                path.write_bytes(safe)
                altered.append(str(path.relative_to(root)))
    return altered


def image_digest(image: str) -> str:
    inspection = subprocess.run(['container','image','inspect',image],capture_output=True,text=True,timeout=20)
    if inspection.returncode != 0:
        raise RuntimeError('image inspection unavailable')
    return json.loads(inspection.stdout)[0]['id']


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('workspace', type=Path)
    parser.add_argument('--product', choices=['codex', 'claude'], required=True)
    parser.add_argument('--bundle', choices=['baseline', 'candidate'], required=True)
    parser.add_argument('--scenario', choices=['approved', 'status', 'draft', 'standalone'], required=True)
    parser.add_argument('--run-id', required=True)
    parser.add_argument('--native-review-disabled', action='store_true', help='Codex-only observed CLI-review configuration; native agent tools disabled.')
    parser.add_argument('--input-dir', default='input-live-v4')
    parser.add_argument('--image', default='nextjs-document-baseline:20261108')
    args = parser.parse_args()
    if any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in args.run_id): raise ValueError('invalid run-id')
    w = args.workspace.resolve()
    out = w / 'live' / args.run_id
    out.mkdir(parents=True, mode=0o700, exist_ok=False)
    inputs = w / args.input_dir
    if not (inputs / args.bundle / 'skills').is_dir(): raise ValueError('frozen skills missing')
    prompt = ('$ains' if args.product == 'codex' else '/ains')
    if args.scenario == 'standalone':
        prompt = ('$ains-build' if args.product == 'codex' else '/ains-build') + ' docs/changes/ains-attribute の承認済みタスクだけを実装してください。今回は build 単独の依頼であり、ship・PR資料作成は依頼していません。指定範囲のローカル編集・検査だけを許可します。'
    elif args.scenario == 'status':
        prompt += ' docs/changes/ains-attribute の現在の状態と次の工程だけを示してください。実行依頼ではありません。ファイルを変更しないでください。'
    else:
        prompt += ' docs/changes/ains-attribute の変更を、記載された範囲で実装・検証・独立レビュー・ローカル出荷資料の準備まで進めてください。承認済み範囲の工程は続けてください。未承認のものは承認を待ち、承認を捏造しないでください。操作は指定されたローカル編集と検査だけです。コミット・push・PR作成・merge・deployは禁止。'
    launcher = Path(__file__).read_bytes()
    publish(out/'launcher.py',launcher)
    public = {'launcherSha256':hashlib.sha256(launcher).hexdigest(), 'product': args.product, 'bundle': args.bundle, 'scenario': args.scenario, 'prompt': prompt, 'inputsSha256': digest_tree(inputs), 'image': args.image, 'timeoutSeconds': 240, 'startedAt': datetime.now(timezone.utc).isoformat(), 'authentication': 'subscription only; private cache excluded from hashes and evidence', 'resume': 'forbidden'}
    public['resolvedImageDigest'] = image_digest(args.image)
    publish(out/'launch.json',(json.dumps(public,ensure_ascii=False,indent=2)+'\n').encode())
    private = Path(tempfile.mkdtemp(prefix='ains-codex-auth-', dir=w))
    private.chmod(0o700)
    env = os.environ.copy()
    for key in ('ANTHROPIC_API_KEY', 'OPENAI_API_KEY', 'CODEX_API_KEY'):
        env.pop(key, None)
    mounts = ['--mount', f'type=bind,source={inputs},target=/inputs,readonly', '--mount', f'type=bind,source={out},target=/evidence']
    container_name = 'ains-live-' + args.run_id.lower()
    secrets = set()
    raw = None
    result_meta = {}
    artifact_walk_safe = False
    try:
        if args.product == 'codex':
            source = Path(os.environ.get('CODEX_HOME', Path.home()/'.codex')) / 'auth.json'
            if not source.is_file(): raise AuthenticationUnavailable('ChatGPT auth cache unavailable')
            shutil.copyfile(source, private / 'auth.json')
            (private / 'auth.json').chmod(0o600)
            secrets.update(auth_strings(private / 'auth.json'))
            mounts += ['--mount', f'type=bind,source={private},target=/private-codex']
            command = ['codex', 'exec', '--ignore-user-config', '--ignore-rules', '--ephemeral', '--json', '-m', 'gpt-6.1-sol', '-c', 'model_reasoning_effort="medium"', '--dangerously-bypass-approvals-and-sandbox', prompt]
            envargs = ['-e', 'CODEX_HOME=/private-codex']
            if args.native_review_disabled:
                review_cache = private/'review-cache'
                review_cache.mkdir(mode=0o700)
                shutil.copyfile(source,review_cache/'auth.json')
                (review_cache/'auth.json').chmod(0o600)
                secrets.update(auth_strings(review_cache/'auth.json'))
                mounts += ['--mount', f'type=bind,source={review_cache},target=/private-review-codex']
                envargs += ['-e','AINS_REVIEW_MODE=cli-only']
                command[-1:-1] = ['--disable','multi_agent','--disable','multi_agent_v2']
                public['nativeReviewConfiguration'] = 'multi_agent and multi_agent_v2 explicitly disabled; installed CLI read-only reviewer with independent private cache required'
        else:
            if not env.get('CLAUDE_CODE_OAUTH_TOKEN'): raise AuthenticationUnavailable('CLAUDE_CODE_OAUTH_TOKEN unavailable')
            command = ['/tmp/ains-claude/node_modules/.bin/claude', '-p', prompt, '--output-format', 'stream-json', '--verbose', '--model', 'sonnet', '--effort', 'medium', '--max-turns', '24', '--permission-mode', 'acceptEdits', '--allowedTools', 'Read,Write,Edit,Bash,Skill,Glob,Grep']
            envargs = ['-e', 'CLAUDE_CODE_OAUTH_TOKEN']
            secrets.add(env['CLAUDE_CODE_OAUTH_TOKEN'])
        # No secret appears in argv or the public launch manifest.
        install = '' if args.product == 'codex' else 'env -u CLAUDE_CODE_OAUTH_TOKEN npm install --prefix /tmp/ains-claude --no-audit --no-fund @anthropic-ai/claude-code@2.1.319 && /tmp/ains-claude/node_modules/.bin/claude --version && '
        preflight = install + 'python3 /inputs/container_case.py auth-preflight --product ' + args.product + ' && '
        wrapper = preflight + 'python3 /inputs/container_case.py setup-live --bundle ' + args.bundle + ' --scenario ' + args.scenario + ' && { "$@"; code=$?; python3 /inputs/container_case.py collect || { echo "ains-collect-failed agent-exit=$code" >&2; exit ' + str(COLLECT_FAILED_EXIT) + '; }; exit $code; }'
        argv = ['container', 'run', '--rm', '--name', container_name, '--cpus', '2', '--memory', '3G', *mounts, *envargs, args.image, 'sh', '-c', wrapper, 'ains-live', *command]
        public['cliArgv'] = command
        public['runtimeInstall'] = install or 'none (image-pinned CLI)'
        publish(out/'launch.json',redact((json.dumps(public,ensure_ascii=False,indent=2)+'\n').encode(),secrets))
        raw, result_meta = capture(argv, env=env, name=container_name)
        secrets.update(auth_strings(private / 'auth.json'))
        secrets.update(auth_strings(private / 'review-cache' / 'auth.json'))
        safe = redact(raw, secrets)
        if result_meta.get('cleanup') == 'cleanup failure':
            failure = {'status':'blocked','failureCode':'container-cleanup-failed','capture':result_meta,'quarantined':True,'stopRequiredContainer':container_name}
            publish(out/'events.sanitized.log',safe)
            publish(out/'result.json',redact((json.dumps(failure,indent=2)+'\n').encode(),secrets))
            print(redact(json.dumps({'run':str(out),**failure}).encode(),secrets).decode())
            return 1
        artifact_walk_safe = True
        altered = sanitize_artifacts(out, secrets)
        publish(out/'events.sanitized.log', safe)
        result_meta['launcherOrigin'] = 'payload marker and stderr require manual inspection'
        result_meta['redactedArtifacts'] = altered
        if altered:
            result_meta['adjudication'] = 'oracle-fail: secret detected in artifact'
        exit_code = result_meta.get('exitCode')
        files_present = all((out/name).is_file() and not (out/name).is_symlink() for name in COLLECTED_EVIDENCE)
        collected = exit_code != COLLECT_FAILED_EXIT and files_present
        result_meta['evidenceCollection'] = 'complete' if collected else 'incomplete'
        # Attribute the failure to collection only when it is the cause: the reserved
        # collector exit, or an otherwise successful run without its evidence. Timeouts
        # and preflight/setup/agent failures keep their own status and exit code.
        if exit_code == COLLECT_FAILED_EXIT or (exit_code == 0 and not files_present):
            result_meta['failureCode'] = 'evidence-collection-failed'
            result_meta['status'] = 'blocked'
        payload = json.dumps(result_meta, indent=2).encode() + b'\n'
        publish(out/'result.json', redact(payload, secrets))
        diagnostic = json.dumps({'run': str(out), **result_meta}).encode()
        print(redact(diagnostic, secrets).decode())
        return 0 if result_meta.get('exitCode') == 0 and collected and not altered else 1
    except (RuntimeError, OSError, subprocess.SubprocessError, ValueError) as error:
        if isinstance(error, AuthenticationUnavailable):
            code = 'authentication-unavailable'
        elif isinstance(error, EvidenceValidationError):
            code = 'evidence-validation-failed'
        else:
            code = 'execution-error'
        failure = {'status':'blocked', 'failureCode':code, 'capture':result_meta}
        if raw is not None:
            publish(out/'events.sanitized.log', redact(raw, secrets))
        publish(out/'result.json', redact((json.dumps(failure,indent=2)+'\n').encode(), secrets))
        print(redact(json.dumps({'run':str(out), **failure}).encode(),secrets).decode())
        return 1
    finally:
        shutil.rmtree(private)
        for p in out.rglob('*') if artifact_walk_safe else ():
            if not p.is_symlink() and stat.S_ISREG(p.lstat().st_mode):
                descriptor = os.open(p, os.O_RDONLY | os.O_NOFOLLOW)
                try:
                    if stat.S_ISREG(os.fstat(descriptor).st_mode):
                        os.fchmod(descriptor, 0o600)
                finally:
                    os.close(descriptor)


if __name__ == '__main__': raise SystemExit(main())
